function tx(
  overrides: Partial<RawTransaction> &
    Pick<RawTransaction, "tx_id" | "tx_status" | "merchant_id" | "merchant_name" | "in_amount">,
): RawTransaction {
  const inAmount = overrides.in_amount;
  const merchantRate = overrides.merchant_rate ?? 92.5;
  const providerRate = overrides.provider_rate ?? 93.0;
  const baseRate = overrides.base_rate ?? 91.8;
  const merchantFeePct = overrides.merchant_fee_pct ?? 2.5;
  const providerFeePct = overrides.provider_fee_pct ?? 1.5;
  const feeAmount = Number(((inAmount * merchantFeePct) / 100).toFixed(2));
  const outAmount = Number((inAmount / merchantRate).toFixed(2));

  return {
    tx_id: overrides.tx_id,
    tx_direction: overrides.tx_direction ?? "P2P_FIAT_IN",
    tx_status: overrides.tx_status,
    merchant_id: overrides.merchant_id,
    merchant_name: overrides.merchant_name,
    allow_variable_amount_on_creation: overrides.allow_variable_amount_on_creation ?? false,
    geo: overrides.geo ?? "BR",
    merchant_tx_id: overrides.merchant_tx_id ?? `MTX-${overrides.tx_id}`,
    merchant_client_id: overrides.merchant_client_id ?? `CLI-${overrides.merchant_id.slice(0, 8)}`,
    merchant_fee_pct: merchantFeePct,
    merchant_rate: merchantRate,
    merchant_out_amount: outAmount,
    merchant_out_amount_confirmed: overrides.tx_status === "TX_SUCCESS" ? outAmount : 0,
    provider: overrides.provider ?? "TESTPROVIDER",
    provider_fee_pct: providerFeePct,
    provider_tx_id: overrides.provider_tx_id ?? `PTX-${overrides.tx_id}`,
    provider_rate: providerRate,
    base_rate: baseRate,
    provider_out_amount: Number((inAmount / providerRate).toFixed(2)),
    provider_out_amount_confirmed:
      overrides.tx_status === "TX_SUCCESS" ? Number((inAmount / providerRate).toFixed(2)) : 0,
    payment_method: overrides.payment_method ?? "INSTANTPAY",
    payment_system: overrides.payment_system ?? "INSTANTPAY",
    payment_requisite_full_name: overrides.payment_requisite_full_name ?? "Ivanov Ivan Ivanovich",
    widget_id: overrides.widget_id ?? `WID-${overrides.merchant_id.slice(0, 6)}`,
    payment_requisite: overrides.payment_requisite ?? "+7900***1234",
    payment_expires_at: overrides.payment_expires_at ?? "2026-03-30T23:59:59Z",
    in_currency: overrides.in_currency ?? "RUB",
    in_amount: inAmount,
    in_amount_confirmed: overrides.tx_status === "TX_SUCCESS" ? inAmount : 0,
    out_currency: overrides.out_currency ?? "USDT",
    fee_currency: overrides.fee_currency ?? "USDT",
    fee_amount: feeAmount,
    is_variable_amount: overrides.is_variable_amount ?? false,
    in_amount_initial: overrides.in_amount_initial ?? inAmount,
    bank_name_requested: overrides.bank_name_requested ?? "Northbridge Bank",
    fee_amount_confirmed: overrides.tx_status === "TX_SUCCESS" ? feeAmount : 0,
    is_requisite_pool: overrides.is_requisite_pool ?? false,
    is_balance_released: overrides.is_balance_released ?? overrides.tx_status === "TX_SUCCESS",
    is_balance_reserved: overrides.is_balance_reserved ?? overrides.tx_status === "TX_ACTIVE",
    is_manual_confirmed: overrides.is_manual_confirmed ?? false,
    base_rate_type: overrides.base_rate_type ?? "MARKET",
    payment_link_qr_national: overrides.payment_link_qr_national ?? "",
    payment_link_bank_direct: overrides.payment_link_bank_direct ?? "",
    created_at: overrides.created_at ?? "2026-03-30T10:00:00Z",
    updated_at: overrides.updated_at ?? "2026-03-30T10:05:00Z",
    completed_at:
      overrides.completed_at ??
      (overrides.tx_status === "TX_SUCCESS" ? "2026-03-30T10:10:00Z" : ""),
  };
}

